// Command gen writes the generated tables of package nepdate from shared/data/.
//
// Run it from the repository root, usually through go generate ./... . With -check it
// generates in memory, compares the bytes with the files on disk, prints the name of each file
// that differs and exits 1, without writing anything (ADR-0001 §5).
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
)

const header = "// Code generated by internal/gen. DO NOT EDIT.\n"

const (
	minYear = 1901
	maxYear = 2199
	years   = maxYear - minYear + 1
)

// output is one generated file, its path relative to the repository root.
type output struct {
	path string
	data []byte
}

// calendarFile is the part of bs-calendar.json the generator reads.
type calendarFile struct {
	MinYear      int              `json:"min_year"`
	MaxYear      int              `json:"max_year"`
	MonthLengths map[string][]int `json:"month_lengths"`
}

// calendar holds the validated month lengths, index 0 is BS 1901.
type calendar struct {
	lengths [years][12]int
}

func main() {
	checkOnly := flag.Bool("check", false, "compare generated files with the files on disk; write nothing")
	flag.Parse()
	if err := run(".", *checkOnly); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(root string, checkOnly bool) error {
	files, err := generate(root)
	if err != nil {
		return err
	}
	if !checkOnly {
		return writeFiles(root, files)
	}
	diff, err := check(root, files)
	if err != nil {
		return err
	}
	for _, path := range diff {
		fmt.Fprintln(os.Stderr, "gen: out of date:", path)
	}
	if len(diff) > 0 {
		return errors.New("generated files differ from shared/data; run go generate ./...")
	}
	return nil
}

// generate builds every generated file in memory.
func generate(root string) ([]output, error) {
	raw, err := os.ReadFile(filepath.Join(root, "shared", "data", "calendar", "bs-calendar.json"))
	if err != nil {
		return nil, err
	}
	var file calendarFile
	if err := json.Unmarshal(raw, &file); err != nil {
		return nil, fmt.Errorf("bs-calendar.json: %w", err)
	}
	cal, err := parseCalendar(&file)
	if err != nil {
		return nil, err
	}
	src, err := renderCalendar(cal)
	if err != nil {
		return nil, err
	}
	return []output{{path: "calendar_gen.go", data: src}}, nil
}

// parseCalendar checks the range and that every year has 12 months of 29 to 32 days.
func parseCalendar(file *calendarFile) (*calendar, error) {
	if file.MinYear != minYear || file.MaxYear != maxYear {
		return nil, fmt.Errorf("bs-calendar.json: range %d..%d, want %d..%d",
			file.MinYear, file.MaxYear, minYear, maxYear)
	}
	cal := &calendar{}
	for i := range years {
		y := minYear + i
		months, ok := file.MonthLengths[strconv.Itoa(y)]
		if !ok {
			return nil, fmt.Errorf("bs-calendar.json: year %d missing", y)
		}
		if len(months) != 12 {
			return nil, fmt.Errorf("bs-calendar.json: year %d has %d months, want 12", y, len(months))
		}
		for m, n := range months {
			if n < 29 || n > 32 {
				return nil, fmt.Errorf("bs-calendar.json: year %d month %d has %d days, want 29..32", y, m+1, n)
			}
			cal.lengths[i][m] = n
		}
	}
	if len(file.MonthLengths) != years {
		return nil, fmt.Errorf("bs-calendar.json: %d years, want %d", len(file.MonthLengths), years)
	}
	return cal, nil
}

func renderCalendar(_ *calendar) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("\npackage nepdate\n\n")
	b.WriteString("const (\n\tminYear = 1901\n\tmaxYear = 2199\n)\n")
	return gofmt("calendar_gen.go", b.Bytes())
}

func gofmt(name string, src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	return out, nil
}

func writeFiles(root string, files []output) error {
	for _, f := range files {
		if err := os.WriteFile(filepath.Join(root, f.path), f.data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// check returns the paths whose bytes on disk differ from the generated bytes, including
// missing files.
func check(root string, files []output) ([]string, error) {
	var diff []string
	for _, f := range files {
		disk, err := os.ReadFile(filepath.Join(root, f.path))
		if errors.Is(err, os.ErrNotExist) {
			diff = append(diff, f.path)
			continue
		}
		if err != nil {
			return nil, err
		}
		if !bytes.Equal(disk, f.data) {
			diff = append(diff, f.path)
		}
	}
	return diff, nil
}
